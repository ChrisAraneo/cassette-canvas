const toLookLegend = (
  hair: number,
  skin: number,
  top: number,
  legs: number,
): SpriteLegend =>
  Object.freeze({
    h: hair,
    s: skin,
    c: toPixel(top, 5),
    C: toPixel(top, 3),
    p: toPixel(legs, 3),
    P: toPixel(legs, 2),
    o: toPixel(GRAY, 0),
  });

